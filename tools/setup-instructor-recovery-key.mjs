import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { createHash, generateKeyPairSync } from "node:crypto";

const repoRoot = process.cwd();
const privateDirectory = path.join(
    os.homedir(),
    "Documents",
    "ECGame-Instructor-Recovery"
);
const privateKeyPath = path.join(privateDirectory, "instructor-private-key.pem");
const publicModulePath = path.join(repoRoot, "src/app/InstructorRecoveryPublicKey.js");

if (!fs.existsSync(path.join(repoRoot, "src/app/GameState.js"))) {
    throw new Error("Run this command from the root of the ecgame repository.");
}
if (fs.existsSync(privateKeyPath)) {
    throw new Error(
        `A private recovery key already exists at ${privateKeyPath}. It was not replaced.`
    );
}

const { privateKey, publicKey } = generateKeyPairSync("ec", {
    namedCurve: "prime256v1"
});
const privatePem = privateKey.export({ type: "pkcs8", format: "pem" });
const publicDer = publicKey.export({ type: "spki", format: "der" });
const spkiBase64 = publicDer.toString("base64");
const keyId = createHash("sha256").update(publicDer).digest("hex").slice(0, 16);

fs.mkdirSync(privateDirectory, { recursive: true, mode: 0o700 });
fs.writeFileSync(privateKeyPath, privatePem, { mode: 0o600, flag: "wx" });
fs.writeFileSync(
    publicModulePath,
    `// Generated by tools/setup-instructor-recovery-key.mjs.\n` +
    `// The public key is safe to commit. Never commit the matching private PEM file.\n` +
    `const InstructorRecoveryPublicKey = {\n` +
    `    keyId: ${JSON.stringify(keyId)},\n` +
    `    spkiBase64: ${JSON.stringify(spkiBase64)}\n` +
    `};\n\nexport default InstructorRecoveryPublicKey;\n`,
    "utf8"
);

console.table({
    result: "INSTRUCTOR RECOVERY KEY CREATED",
    keyId,
    privateKey: privateKeyPath,
    publicModule: publicModulePath
});
console.log("Back up the private PEM securely. Never add it to Git or give it to students.");
